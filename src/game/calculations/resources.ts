import { SpacecraftComponent, LaunchVehicle, OrbitConfiguration } from '../../types/game';

export interface CalculatedResources {
  dryMassKg: number;
  propellantMassKg: number;
  totalMassKg: number;
  spacecraftCost: number; // in $1,000 USD
  launchCost: number;
  totalCost: number;
  powerGenW: number;
  powerDrawW: number;
  netPowerW: number;
  batteryCapacityWh: number;
  batteryReserveMinutes: number;
  totalDeltaVMs: number;
  dataGenMbps: number;
  storageCapacityGb: number;
  downlinkRateMbps: number;
  thermalDissipationW: number;
  thermalBalanceTempC: number;
  reliabilityIndex: number;
}

export function calculateSpacecraftResources(
  components: SpacecraftComponent[],
  launchVehicle?: LaunchVehicle,
  orbit?: OrbitConfiguration
): CalculatedResources {
  let dryMassKg = 0;
  let propellantMassKg = 0;
  let spacecraftCost = 0;
  let rawSolarPowerGen = 0;
  let rtgPowerGen = 0;
  let powerDrawW = 0;
  let batteryCapacityWh = 0;
  let weightedIspSum = 0;
  let totalPropellantForIsp = 0;
  let dataGenMbps = 0;
  let storageCapacityGb = 0;
  let antennaGainFactor = 1.0;
  let transmitterPowerFactor = 1.0;
  let thermalDissipationW = 0;
  let reliabilityProduct = 1.0;

  for (const comp of components) {
    dryMassKg += comp.mass;
    spacecraftCost += comp.cost;
    powerDrawW += comp.powerDraw;
    dataGenMbps += comp.dataGen;
    storageCapacityGb += comp.dataStorage;
    thermalDissipationW += comp.thermalRating;
    reliabilityProduct *= Math.min(1.0, Math.max(0.5, comp.reliability));

    // Power generation distinction (RTG vs Solar)
    if (comp.meshType === 'rtg_unit') {
      rtgPowerGen += comp.powerGen;
    } else if (comp.powerGen > 0) {
      rawSolarPowerGen += comp.powerGen;
    }

    // Battery capacity
    if (comp.meshType === 'battery_bank') {
      batteryCapacityWh += 1200; // 1.2 kWh per battery bank
    }

    // Propulsion
    if (comp.propellantMass && comp.propellantMass > 0) {
      propellantMassKg += comp.propellantMass;
      const isp = comp.isp || 300;
      weightedIspSum += isp * comp.propellantMass;
      totalPropellantForIsp += comp.propellantMass;
    }

    // Communications
    if (comp.meshType === 'antenna_hga_dish') {
      antennaGainFactor *= 4.5;
    } else if (comp.meshType === 'antenna_omni') {
      antennaGainFactor *= 1.2;
    }
    if (comp.meshType === 'transponder') {
      transmitterPowerFactor *= 3.0;
    }
  }

  // Base battery reserve from bus even if no dedicated battery
  if (batteryCapacityWh === 0 && components.length > 0) {
    batteryCapacityWh = 150; // default internal bus backup
  }

  // Solar flux scaling according to orbit/destination
  const solarFlux = orbit ? orbit.solarFluxMultiplier : 1.0;
  const solarGenW = rawSolarPowerGen * solarFlux;
  const powerGenW = Math.round(solarGenW + rtgPowerGen);
  const netPowerW = powerGenW - powerDrawW;

  // Battery endurance during eclipse
  const batteryReserveMinutes = powerDrawW > 0 
    ? Math.round((batteryCapacityWh / powerDrawW) * 60)
    : 999;

  // Tsiolkovsky Rocket Equation: Delta-V = Isp * g0 * ln((m_dry + m_prop) / m_dry)
  let totalDeltaVMs = 0;
  if (propellantMassKg > 0 && dryMassKg > 0) {
    const averageIsp = totalPropellantForIsp > 0 ? (weightedIspSum / totalPropellantForIsp) : 310;
    const g0 = 9.80665;
    const massRatio = (dryMassKg + propellantMassKg) / dryMassKg;
    totalDeltaVMs = Math.round(averageIsp * g0 * Math.log(massRatio));
  }

  // Downlink data rate calculation based on distance and antenna system
  const commDelay = orbit ? orbit.commDelaySeconds : 0.01;
  // Free space loss approximation
  const distanceFactor = Math.max(0.1, 100 / Math.max(1, commDelay * 10));
  const baseDownlink = Math.min(120, Math.max(2, 15 * antennaGainFactor * transmitterPowerFactor * (distanceFactor / 50)));
  const downlinkRateMbps = Math.round(baseDownlink * 10) / 10;

  // Thermal balance estimation
  // Heat generated by electronics + solar absorption vs radiation dissipation
  const netHeatLoadW = powerDrawW * 0.9;
  const thermalBalanceTempC = Math.round(20 + ((netHeatLoadW - thermalDissipationW) * 0.25));

  const totalMassKg = dryMassKg + propellantMassKg;
  const launchCost = launchVehicle ? launchVehicle.cost : 0;
  const totalCost = spacecraftCost + launchCost;

  // Spacecraft overall reliability (geometric combination)
  const count = Math.max(1, components.length);
  const reliabilityIndex = Math.round(Math.pow(reliabilityProduct, 1 / count) * 100) / 100;

  return {
    dryMassKg,
    propellantMassKg,
    totalMassKg,
    spacecraftCost,
    launchCost,
    totalCost,
    powerGenW,
    powerDrawW,
    netPowerW,
    batteryCapacityWh,
    batteryReserveMinutes,
    totalDeltaVMs,
    dataGenMbps,
    storageCapacityGb,
    downlinkRateMbps,
    thermalDissipationW,
    thermalBalanceTempC,
    reliabilityIndex
  };
}
